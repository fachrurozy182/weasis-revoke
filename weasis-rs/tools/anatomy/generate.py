"""Generate `crates/weasis-core/src/dicom/anatomy/body_parts.rs` from weasis-dicom-tools.

Development tool only. The table of body parts (DICOM PS3.16 CID 4031 / Table L-1) is taken
verbatim from the Java enum so that both viewers resolve anatomy the same way.

Usage (from `weasis-rs/`):
    python3 tools/anatomy/generate.py ../../fachrurozy182/weasis-dicom-tools
"""

import re
import sys
from pathlib import Path

ENUM_ENTRY = re.compile(
    r"^\s+([A-Z0-9_]+)\((SCT|DCM), (\d+), \"([^\"]*)\", (true|false), (true|false), (true|false)\)[,;]"
)


def main() -> None:
    tools_repo = Path(sys.argv[1])
    ref = tools_repo / "weasis-dicom-tools/src/main"
    java = (ref / "java/org/weasis/dicom/ref/BodyPart.java").read_text(encoding="utf-8")
    srt = (ref / "resources/org/weasis/dicom/ref/bodyPartSrt.properties").read_text(encoding="utf-8")

    parts = [ENUM_ENTRY.match(line) for line in java.splitlines()]
    parts = [m.groups() for m in parts if m]
    names = {name for name, *_ in parts}
    retired = sorted(
        (key.strip(), value.strip())
        for key, value in (line.split("=", 1) for line in srt.splitlines()
                           if "=" in line and not line.startswith("#"))
        if value.strip() in names
    )

    out = Path(__file__).resolve().parents[2] / "crates/weasis-core/src/dicom/anatomy/body_parts.rs"
    lines = [
        "//! Body parts of DICOM PS3.16 CID 4031 / Table L-1.",
        "//!",
        "//! GENERATED by `tools/anatomy/generate.py` from weasis-dicom-tools `BodyPart.java` and",
        "//! `bodyPartSrt.properties`: do not edit by hand.",
        "",
        "use super::BodyPart;",
        "",
        "/// All body parts: name, coding scheme, code value, Body Part Examined term, paired.",
        "#[rustfmt::skip]",
        "pub const BODY_PARTS: &[BodyPart] = &[",
    ]
    for name, scheme, code, legacy, paired, _common, _endoscopic in parts:
        lines.append(
            f'    BodyPart {{ name: "{name}", scheme: "{scheme}", code: "{code}", '
            f'legacy_code: "{legacy}", paired: {paired} }},'
        )
    lines += [
        "];",
        "",
        "/// Retired SNOMED-RT identifiers (\"SRT\" scheme) and the body part they denote.",
        "#[rustfmt::skip]",
        "pub const RETIRED_SNOMED_RT: &[(&str, &str)] = &[",
    ]
    lines += [f'    ("{key}", "{value}"),' for key, value in retired]
    lines += ["];", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(parts)} body parts, {len(retired)} retired codes written to {out}")


if __name__ == "__main__":
    main()
